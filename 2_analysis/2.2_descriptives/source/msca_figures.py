#!/usr/bin/env python3
"""Generate the MSCA data figures of the introduction (Figures 1 and 2 of the paper).

    python3 msca_figures.py                    # every figure
    python3 msca_figures.py msca_gf_share      # just that one

Writes to output/:
  msca_gf_share.tex     the share of eligible applicants to the MSCA fellowships who applied to
                        the Global (GF) rather than the European (EF) Fellowship, for the SOC,
                        ECO and CHE panels, 2016-2025.
  msca_noise_share.tex  the share of eligible applicants choosing the GF, pooled over 2016-2020,
                        against reviewer disagreement (1 - Gwet's AC, 0-5 grade, IF 2014-2018
                        reviewer scores), for all eight panels, with the least-squares fit
                        across them.

Inputs: the clean tables in 1_data/output (see msca_common.py).
"""

import sys

import numpy as np
from scipy import stats

from msca_common import (OUTDIR, PANELS, YEARS, agreement, counts, grades, place_labels_clear,
                         reviewer_scores)

# panel code, legend name, colour (categorical slots 1-3), marker
SERIES = [
    ("SOC", "Social sciences \\& humanities", "2A78D6", "*"),
    ("ECO", "Economics", "EB6834", "square*"),
    ("CHE", "Chemistry", "1BAF7A", "triangle*"),
]
NOISE_YEARS = list(range(2016, 2021))   # GF/EF window of Figure 2: before the 2021 reform


def figure_gf_share(c):
    share = {(y, p): 100 * c[(y, p)][1] / sum(c[(y, p)]) for y in YEARS for p, *_ in SERIES}
    ymax = 5 * (int(max(share.values()) // 5) + 1)
    lines = [
        "% Share of eligible MSCA applicants who applied to the Global rather than the European",
        "% Fellowship, by panel, 2016-2025. GENERATED BY msca_figures.py - edit that file, not this one.",
        "% Eligible proposals (EF/GF): " + "; ".join(
            f"{p} " + " ".join(f"{y}:{c[(y, p)][0]}/{c[(y, p)][1]}" for y in YEARS) for p, *_ in SERIES),
    ]
    lines += [f"\\definecolor{{msca{p}}}{{HTML}}{{{col}}}" for p, _, col, _ in SERIES]
    lines += [
        "\\begin{figure}[htbp]",
        "\\centering",
        "\\begin{tikzpicture}",
        "\\begin{axis}[",
        "  width=13cm, height=7cm,",
        f"  xmin=2015.6, xmax=2025.4, ymin=0, ymax={ymax},",
        "  xtick={" + ",".join(map(str, YEARS)) + "}, xticklabel style={/pgf/number format/1000 sep={}},",
        "  ytick distance=5, yticklabel={\\pgfmathprintnumber{\\tick}\\%},",
        "  axis x line=bottom, axis y line=left, axis line style={gray!70},",
        "  ymajorgrids, grid style={gray!20},",
        "  tick label style={font=\\footnotesize}, label style={font=\\footnotesize},",
        "  ylabel={Applicants choosing the Global Fellowship},",
        "  clip=false,",
        "]",
    ]
    for p, name, _, mark in SERIES:
        pts = " ".join(f"({y},{share[(y, p)]:.2f})" for y in YEARS)
        lines.append(f"\\addplot[color=msca{p}, line width=1.2pt, mark={mark}, mark size=2pt] coordinates {{{pts}}};")
    for p, *_ in SERIES:   # direct labels at the right end, in text ink (no legend)
        lines.append(f"\\node[font=\\footnotesize, anchor=west] at (axis cs:2025.15,{share[(2025, p)]:.2f}) {{{p}}};")
    lines += [
        "\\end{axis}",
        "\\end{tikzpicture}",
        "\\caption{\\footnotesize Share of eligible applicants to the Marie Sk\\l{}odowska-Curie Actions postdoctoral",
        "fellowships who applied to the Global rather than the European Fellowship, by panel, 2016--2025.",
        "SOC: social sciences and humanities; ECO: economics; CHE: chemistry. Both EF and GF were introduced in 2014. However, 2016 "
        "is the earliest year where there is public data on application counts for each scientific field. In 2014 and 2015, "
        "field-specific application counts across all fields are not publicly available.}",
        "\\label{fig:msca_gf_share}",
        "\\end{figure}",
        "",
    ]
    (OUTDIR / "msca_gf_share.tex").write_text("\n".join(lines))
    print("  wrote output/msca_gf_share.tex")
    for p, *_ in SERIES:
        print(f"  {p}: " + "  ".join(f"{y} {share[(y, p)]:.1f}%" for y in YEARS))


def figure_noise_share(c):
    R = reviewer_scores()
    ac = {p: agreement(grades(R[p][0])) for p in PANELS}
    d = {p: 1 - ac[p]["gwet"] for p in PANELS}                    # disagreement
    dse = {p: ac[p]["gwet_se"] for p in PANELS}
    G = {p: sum(c[(y, p)][1] for y in NOISE_YEARS) for p in PANELS}
    N = {p: sum(sum(c[(y, p)]) for y in NOISE_YEARS) for p in PANELS}
    s = {p: 100 * G[p] / N[p] for p in PANELS}                     # pooled = applicant-weighted average share
    sse = {p: 100 * np.sqrt(G[p] / N[p] * (1 - G[p] / N[p]) / N[p]) for p in PANELS}

    fits = {}                    # "all" is drawn; the other two are reported in the log
    for key, fs in (("all", PANELS), ("nophy", [p for p in PANELS if p != "PHY"]),
                    ("nosoc", [p for p in PANELS if p != "SOC"])):
        f = stats.linregress([d[p] for p in fs], [s[p] for p in fs])
        fits[key] = (f.intercept, f.slope, f.rvalue ** 2, f.pvalue)

    lo = min(d[p] - 1.96 * dse[p] for p in PANELS); hi = max(d[p] + 1.96 * dse[p] for p in PANELS)
    xlo, xhi = lo - 0.06 * (hi - lo), hi + 0.06 * (hi - lo)
    ylo, yhi = 0, 5 * int(np.ceil((max(s.values()) + 2) / 5))       # headroom above the top point
    w_cm, h_cm = 12.9, 6.9                                           # plot-area size (measured)
    norm = {p: ((d[p] - xlo) / (xhi - xlo), (s[p] - ylo) / (yhi - ylo)) for p in PANELS}
    a, b, r2, _ = fits["all"]
    seg = [((x - xlo) / (xhi - xlo), (a + b * x - ylo) / (yhi - ylo)) for x in (xlo, xhi)]
    lab = place_labels_clear(norm, {p: 1.96 * dse[p] / (xhi - xlo) for p in PANELS},
                             {p: 1.96 * sse[p] / (yhi - ylo) for p in PANELS}, seg, None, w_cm, h_cm,
                             {p: p for p in PANELS})
    lab = {p: (xlo + u * (xhi - xlo), ylo + v * (yhi - ylo)) for p, (u, v) in lab.items()}   # data units

    lines = [
        "% Share of eligible applicants choosing the GF (pooled 2016-2020) against reviewer disagreement",
        "% (1 - Gwet's AC, 0-5 grade, power-1/4 weights, IF 2014-2018 reviewer scores), by MSCA panel; all eight panels.",
        "% GENERATED BY msca_figures.py - edit that file, not this one.",
        "% " + "; ".join(f"{p}: 1-AC {d[p]:.3f} (SE {dse[p]:.4f}), GF {G[p]} of {N[p]} = {s[p]:.2f}%" for p in PANELS),
        "% fits (share on disagreement): " + "; ".join(
            f"{k}: slope {fb:.1f} pp per unit, R2 {fr2:.2f}, p {pv:.3f}" for k, (_, fb, fr2, pv) in fits.items()),
        "\\definecolor{msca1}{HTML}{2A78D6}",
        "\\begin{figure}[htbp]",
        "\\centering",
        "\\begin{tikzpicture}",
        "\\begin{axis}[",
        "  width=14.5cm, height=8.5cm,",                      # a little wider: room for the middle cluster
        f"  xmin={xlo:.4f}, xmax={xhi:.4f}, ymin={ylo}, ymax={yhi},",
        "  xtick distance=0.02, minor x tick num=1,",          # minor ticks every 0.01 to read the middle cluster
        "  xticklabel style={/pgf/number format/.cd, fixed, fixed zerofill, precision=2},",
        "  ytick distance=5, yticklabel={\\pgfmathprintnumber{\\tick}\\%},",
        "  axis x line=bottom, axis y line=left, axis line style={gray!70},",
        "  ymajorgrids, grid style={gray!20},",
        "  tick label style={font=\\footnotesize}, label style={font=\\footnotesize},",
        "  xlabel={Reviewer disagreement: $1-{}$Gwet's AC},",
        "  ylabel={Share of total applicants who choose GF},",
        "  clip=false,",
        "]",
        f"\\addplot[gray!70!black, line width=1pt, dashed, domain={xlo:.4f}:{xhi:.4f}, samples=2] "
        f"{{{a:.5f}+{b:.5f}*x}};",
    ]
    rows = " \\\\ ".join(f"{d[p]:.5f} {s[p]:.4f} {1.96 * dse[p]:.5f} {1.96 * sse[p]:.4f}" for p in PANELS)
    # white rings round the marks and lighter, thinner bars keep the middle cluster apart
    lines += [
        "\\addplot[only marks, mark=*, mark size=2.6pt, color=msca1, forget plot,",
        "  mark options={fill=msca1, draw=white, line width=0.6pt},",
        "  error bars/.cd, x dir=both, x explicit, y dir=both, y explicit,",
        "  error bar style={color=msca1!60, line width=0.6pt}]",
        "  table[row sep=\\\\, x=d, y=s, x error=dx, y error=ds]",
        f"  {{d s dx ds \\\\ {rows} \\\\}};",
    ]
    # labels centred where place_labels_clear found room clear of the intervals, marks and fit
    lines += [f"\\node[font=\\footnotesize, anchor=center] at (axis cs:{lab[p][0]:.5f},{lab[p][1]:.4f}) {{{p}}};"
              for p in PANELS]
    lines += [
        "\\end{axis}",
        "\\end{tikzpicture}",
        "\\caption{\\footnotesize Share of eligible applicants who applied to the Global rather than the European",
        "Fellowship, pooled over 2016--2020, against reviewer disagreement, by MSCA panel. Disagreement is one minus",
        "Gwet's AC, computed from the three reviewer scores of each submission in 2014--2018,",
        "grouped into the six grades of the 0--5 scale used to evaluate application proposals in the GF/EF program. Bars are 95 percent",
        "confidence intervals.",
        "CHE: chemistry; ECO: economics; ENG: information science and engineering; ENV: environment and geosciences;",
        "LIF: life sciences; MAT: mathematics; PHY: physics; SOC: social sciences and humanities.}",
        "\\label{fig:msca_noise_share}",
        "\\end{figure}",
        "",
    ]
    (OUTDIR / "msca_noise_share.tex").write_text("\n".join(lines))
    print("  wrote output/msca_noise_share.tex")
    print("  Gwet's AC (all panels): " + "  ".join(
        f"{p} {ac[p]['gwet']:.3f} ({ac[p]['gwet_se']:.3f})" for p in PANELS))
    print("  GF share 2016-20: " + "  ".join(f"{p} {s[p]:.1f}%" for p in PANELS))
    sd = np.std([d[p] for p in PANELS], ddof=1)
    for k, (_, fb, fr2, pv) in fits.items():
        print(f"  fit {k}: slope {fb:.1f}, R2 {fr2:.2f}, p {pv:.3f}, {fb * sd:.1f} pp per SD of disagreement")


TARGETS = {"msca_gf_share": figure_gf_share, "msca_noise_share": figure_noise_share}

if __name__ == "__main__":
    names = sys.argv[1:] or list(TARGETS)          # no argument: build every figure
    unknown = [n for n in names if n not in TARGETS]
    if unknown:
        sys.exit(f"unknown target(s) {unknown}; choose from {list(TARGETS)}")
    OUTDIR.mkdir(exist_ok=True)
    c = counts()
    for n in names:
        TARGETS[n](c)
